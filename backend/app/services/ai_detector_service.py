def calculate_burstiness(sentences: List[str]) -> float:
    """
    Computes sentence length burstiness (standard deviation of word counts).
    AI text exhibits low burstiness (uniform sentence lengths, ~2-4).
    Human legal drafting exhibits high burstiness (mixing short clauses with dense multi-clause definitions, std > 7).
    """
    if len(sentences) < 3:
        return 5.0
    lengths = [len(s.split()) for s in sentences if len(s.split()) > 2]
    if len(lengths) < 3:
        return 5.0
    mean = sum(lengths) / len(lengths)
    variance = sum((l - mean) ** 2 for l in lengths) / len(lengths)
    return math.sqrt(variance)


def calculate_repetition_rate(text: str) -> float:
    """Detects formulaic sentence beginnings characteristic of LLM templates."""
    sentences = [s.strip() for s in re.split(r"[.!?\n]+", text) if len(s.strip()) > 10]
    if not sentences:
        return 0.0
    openers = []
    for s in sentences:
        words = s.split()
        if len(words) >= 2:
            openers.append(" ".join(words[:2]).lower())
    if not openers:
        return 0.0
    counts = {}
    for op in openers:
        counts[op] = counts.get(op, 0) + 1
    repeated = sum(c - 1 for c in counts.values() if c > 1)
    return repeated / len(openers)


def detect_ai_in_document(text: str, filename: str = "") -> Dict[str, Any]:
    """
    Analyzes legal bond or contract text to detect whether it was generated by AI (ChatGPT/Claude/Gemini)
    vs authored by a human legal professional.
    Returns:
    - is_ai_generated: bool
    - ai_detection_score: float (0.0 to 1.0)
    - ai_verdict: str
    - ai_confidence: str ('high', 'medium', 'low')
    - ai_markers: list of flagged clauses with quotes and severity
    - ai_alert_triggered: bool (triggers immediate UI modal alert if True)
    """
    clean_text = text.strip()
    if not clean_text:
        return {
            "is_ai_generated": False,
            "ai_detection_score": 0.0,
            "ai_verdict": "Document is empty",
            "ai_confidence": "low",
            "ai_markers": [],
            "ai_alert_triggered": False,
        }

    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n{2,}", clean_text) if len(s.strip()) > 10]
    detected_markers: List[Dict[str, Any]] = []

    # 1. Check for explicit AI signatures and hallmark LLM patterns
    signature_score = 0.0
    has_critical_signature = False

    for pattern, description, severity in AI_SIGNATURE_PATTERNS:
        matches = list(re.finditer(pattern, clean_text, re.IGNORECASE))
        if matches:
            for match in matches[:2]:  # cap at 2 per rule
                start = max(0, match.start() - 40)
                end = min(len(clean_text), match.end() + 40)
                detected_markers.append({
                    "marker_type": "ai_signature_pattern",
                    "severity": severity,
                    "description": description,
                    "excerpt": clean_text[start:end].strip(),
                })
            if severity == "high":
                signature_score += 0.35
                has_critical_signature = True
            elif severity == "medium":
                signature_score += 0.18
            else:
                signature_score += 0.08

    # 2. Check for Authentic Statutory Legal Markers
    authentic_cites = 0
    for auth_pat in AUTHENTIC_LEGAL_MARKERS:
        if re.search(auth_pat, clean_text, re.IGNORECASE):
            authentic_cites += 1

    # 3. Burstiness (Sentence Length Variance)
    burstiness = calculate_burstiness(sentences)
    burstiness_score = 0.0
    if burstiness < 4.2 and len(sentences) >= 5:
        burstiness_score = 0.25
        detected_markers.append({
            "marker_type": "uniform_burstiness",
            "severity": "medium",
            "description": f"Unnaturally uniform sentence rhythm (variance std: {burstiness:.1f}, typical human drafting std > 7.0)",
            "excerpt": sentences[0][:90] if sentences else None,
        })
    elif burstiness > 8.0:
        burstiness_score = -0.15

    # 4. Repetition rate of formulaic sentence structures
    repetition = calculate_repetition_rate(clean_text)
    repetition_score = 0.0
    if repetition > 0.25:
        repetition_score = 0.20
        detected_markers.append({
            "marker_type": "formulaic_syntax",
            "severity": "medium",
            "description": f"Formulaic repetitive sentence structure ({int(repetition*100)}% repeated clause openers)",
            "excerpt": None,
        })

    # 5. Statutory discount if authentic legal citations exist
    authenticity_discount = min(0.35, authentic_cites * 0.10)

    # 6. Compute Raw AI Score
    base_score = 0.15
    raw_score = base_score + signature_score + burstiness_score + repetition_score - authenticity_discount

    if has_critical_signature:
        raw_score = max(raw_score, 0.78)

    final_score = round(max(0.04, min(0.98, raw_score)), 2)

    # 7. Verdict & Alert determination
    if final_score >= 0.55 or has_critical_signature:
        is_ai = True
        alert_triggered = True
        verdict = "High Risk: AI-Generated Content Detected"
        confidence = "high" if (final_score >= 0.70 or has_critical_signature) else "medium"
    elif final_score >= 0.35:
        is_ai = False
        alert_triggered = False
        verdict = "Mixed / Potential AI-Assisted Drafting"
        confidence = "medium"
    else:
        is_ai = False
        alert_triggered = False
        verdict = "Authentic Human Legal Drafting"
        confidence = "high" if authentic_cites >= 2 else "medium"

    return {
        "is_ai_generated": is_ai,
        "ai_detection_score": final_score,
        "ai_verdict": verdict,
        "ai_confidence": confidence,
        "ai_markers": detected_markers,
        "ai_alert_triggered": alert_triggered,
        "authentic_legal_markers_count": authentic_cites,
        "sentence_burstiness": round(burstiness, 1),
    }


def extract_bond_terms(text: str) -> Dict[str, Any]:
    """
    Extracts structured legal bond and agreement terms from bond documents.
    """
    lines = [l.strip() for l in text.splitlines() if l.strip()]

    # 1. Identify Bond Type
    bond_type = "Indemnity Bond"
    type_matches = [
        (r"indemnity bond", "Indemnity Bond"),
        (r"surety bond", "Surety Bond"),
        (r"performance bond", "Performance Bond"),
        (r"fidelity bond", "Fidelity Bond"),
        (r"bail bond", "Bail Bond"),
        (r"promissory note", "Promissory Note"),
        (r"security deposit bond", "Security Deposit Bond"),
        (r"lease bond", "Lease Bond"),
        (r"stamp paper agreement", "Stamp Paper Agreement"),
        (r"service agreement", "Service Agreement Bond"),
    ]
    for pattern, name in type_matches:
        if re.search(pattern, text, re.IGNORECASE):
            bond_type = name
            break

    # 2. Extract Bond Amount / Penalty Sum
    amount_match = re.search(
        r"(?:sum of|amount of|penalty of|rupees|rs\.?|inr|\$|usd|valuing)\s*[:.]?\s*([₹$€£]?\s*[\d,]+(?:\.\d{2})?)\s*(?:inr|rs|rupees|usd|\$)?",
        text,
        re.IGNORECASE,
    )
    bond_amount = amount_match.group(1).strip() if amount_match else "To be specified"

    # 3. Extract Obligor (Executant) and Obligee (Beneficiary)
    obligor = None
    obligee = None

    bound_match = re.search(
        r"(?:bound unto|in favour of|in favor of)\s+([A-Za-z0-9 .,_-]{3,40})",
        text,
        re.IGNORECASE,
    )
    if bound_match:
        obligee = bound_match.group(1).strip()

    executant_match = re.search(
        r"(?:by and between|executant|i,\s+|we,\s+)([A-Za-z0-9 .,_-]{3,40})(?:,\s*(?:son of|daughter of|resident of|hereinafter))?",
        text,
        re.IGNORECASE,
    )
    if executant_match:
        obligor = executant_match.group(1).strip()

    # 4. Extract Stamp Duty / Folio Details
    stamp_match = re.search(
        r"(?:stamp duty paid|stamp paper value|grn|folio no\.?|certificate no\.?)\s*[:.]?\s*([A-Za-z0-9/-]{4,30})",
        text,
        re.IGNORECASE,
    )
    stamp_ref = stamp_match.group(1).strip() if stamp_match else "Unregistered / Digital Draft"

    # 5. Core Obligation summary
    obligation_text = "Obligor agrees to indemnify and hold harmless the Obligee against all losses, damages, claims, and default penalties arising from non-performance of agreed conditions."
    for line in lines:
        if any(k in line.lower() for k in ["indemnify", "undertake", "guarantee", "bound myself", "covenant", "default"]):
            if len(line) > 20:
                obligation_text = line[:250]
                break

    return {
        "bond_type": bond_type,
        "obligor": obligor or "Principal / Executant",
        "obligee": obligee or "Beneficiary / Obligee",
        "bond_amount": bond_amount,
        "stamp_reference": stamp_ref,
        "core_obligation": obligation_text,
        "default_penalty_terms": f"Full forfeiture of {bond_amount} upon breach of stated conditions without prejudice to statutory legal remedies.",
    }
